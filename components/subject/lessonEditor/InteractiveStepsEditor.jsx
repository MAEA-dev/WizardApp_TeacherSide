import { StyleSheet, Text, TouchableOpacity, View } from "react-native";
import MaterialIcons from "@expo/vector-icons/MaterialIcons";
import { Fredoka, Nunito } from "../../../constants/fonts";
import { LESSON_EDITOR_COLORS as colors } from "./theme";
import InteractiveStepCard from "./InteractiveStepCard";
import NewStepForm from "./NewStepForm";

export default function InteractiveStepsEditor({
  aiStatus,
  steps,
  editingStepIndex,
  draftText,
  onChangeText,
  draftChoices,
  onChangeChoice,
  onAddChoice,
  onRemoveChoice,
  draftAnswer,
  onChangeAnswer,
  editError,
  onToggleEdit,
  onUploadImage,
  onRemoveImage,
  uploadingImageIndex,
  imageCount,
  addingStepType,
  newStepDraft,
  newStepError,
  onStartAdding,
  onChangeNewDraft,
  onChangeNewChoice,
  onAddNewChoice,
  onRemoveNewChoice,
  onCancelAdd,
  onSubmitAdd,
}) {
  return (
    <View>
      <View style={styles.header}>
        <Text style={styles.heading}>Interactive steps</Text>
        <View style={styles.headerBadges}>
          <View style={styles.imageCountBadge}>
            <MaterialIcons name="photo-library" size={12} color={colors.primary} />
            <Text style={styles.badgeText}>{imageCount}/2 photos</Text>
          </View>
          <View style={styles.badge}>
            <MaterialIcons name="auto-awesome" size={12} color={colors.primary} />
            <Text style={styles.badgeText}>
              {aiStatus === "done" ? "Generated by AI" : "AI content"}
            </Text>
          </View>
        </View>
      </View>

      <View style={styles.list}>
        {steps.map(({ step, index }) => (
          <InteractiveStepCard
            key={`interactive-step-${index}`}
            step={step}
            index={index}
            number={index + 1}
            isEditing={editingStepIndex === index}
            draftText={draftText}
            onChangeText={onChangeText}
            draftChoices={draftChoices}
            onChangeChoice={onChangeChoice}
            onAddChoice={onAddChoice}
            onRemoveChoice={onRemoveChoice}
            draftAnswer={draftAnswer}
            onChangeAnswer={onChangeAnswer}
            error={editingStepIndex === index ? editError : ""}
            onToggleEdit={() => onToggleEdit(index, step)}
            onUploadImage={onUploadImage}
            onRemoveImage={onRemoveImage}
            isUploadingImage={uploadingImageIndex === index}
            canUploadImage={imageCount < 2}
          />
        ))}
      </View>

      <View style={styles.addActions}>
        <TouchableOpacity
          accessibilityRole="button"
          onPress={() => onStartAdding("say")}
          style={styles.secondaryAction}
        >
          <MaterialIcons name="add" size={17} color={colors.primary} />
          <Text style={styles.secondaryText}>Add explanation</Text>
        </TouchableOpacity>
        <TouchableOpacity
          accessibilityRole="button"
          onPress={() => onStartAdding("ask")}
          style={styles.secondaryAction}
        >
          <MaterialIcons name="add" size={17} color={colors.primary} />
          <Text style={styles.secondaryText}>Add question</Text>
        </TouchableOpacity>
      </View>

      {addingStepType && (
        <NewStepForm
          type={addingStepType}
          draft={newStepDraft}
          error={newStepError}
          onChangeDraft={onChangeNewDraft}
          onChangeChoice={onChangeNewChoice}
          onAddChoice={onAddNewChoice}
          onRemoveChoice={onRemoveNewChoice}
          onCancel={onCancelAdd}
          onSubmit={onSubmitAdd}
        />
      )}
    </View>
  );
}

const styles = StyleSheet.create({
  header: {
    flexDirection: "row",
    alignItems: "center",
    justifyContent: "space-between",
    flexWrap: "wrap",
    gap: 8,
    marginTop: 14,
    marginBottom: 9,
  },
  heading: {
    color: colors.text,
    fontFamily: Fredoka.semiBold,
    fontSize: 16,
  },
  badge: {
    flexDirection: "row",
    alignItems: "center",
    gap: 4,
    borderRadius: 14,
    backgroundColor: "#E9E6FF",
    paddingHorizontal: 8,
    paddingVertical: 5,
  },
  headerBadges: {
    flexDirection: "row",
    alignItems: "center",
    flexWrap: "wrap",
    gap: 6,
  },
  imageCountBadge: {
    flexDirection: "row",
    alignItems: "center",
    gap: 4,
    borderRadius: 14,
    backgroundColor: "#E9E6FF",
    paddingHorizontal: 8,
    paddingVertical: 5,
  },
  badgeText: {
    color: colors.primary,
    fontFamily: Nunito.bold,
    fontSize: 10,
  },
  list: { gap: 8 },
  addActions: {
    flexDirection: "row",
    flexWrap: "wrap",
    gap: 8,
    marginTop: 10,
  },
  secondaryAction: {
    flexDirection: "row",
    alignItems: "center",
    justifyContent: "center",
    gap: 3,
    minHeight: 36,
    paddingHorizontal: 10,
    borderRadius: 10,
    borderWidth: 1,
    borderColor: colors.border,
    backgroundColor: "#FFFFFF",
  },
  secondaryText: {
    color: colors.primary,
    fontFamily: Nunito.bold,
    fontSize: 11,
  },
});
